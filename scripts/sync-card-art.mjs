import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const CARDS_DIR = path.join(ROOT, 'public', 'assets', 'cards');
const OUTPUT = path.join(ROOT, 'src', 'config', 'cardArt.generated.ts');

const COLLECTIONS = [
  'guardians',
  'dragons',
  'knights',
  'abyss',
  'mages',
  'gods',
  'cosmic',
  'hunters',
];

const EXTENSIONS = ['.webp', '.png', '.jpg', '.jpeg'];

const artwork = {};

for (const collection of COLLECTIONS) {
  const folder = path.join(CARDS_DIR, collection);

  if (!fs.existsSync(folder)) {
    console.warn(`[NEXA ART] Pasta ausente: ${collection}`);
    continue;
  }

  const files = fs.readdirSync(folder);

  for (const file of files) {
    const ext = path.extname(file).toLowerCase();

    if (!EXTENSIONS.includes(ext)) continue;

    const match = file.match(/^(card-[a-z0-9-]+)-v(\d+)\.(webp|png|jpg|jpeg)$/i);

    if (!match) {
      console.warn(`[NEXA ART] Nome ignorado: ${collection}/${file}`);
      continue;
    }

    const templateId = match[1];
    const version = Number(match[2]);

    const candidate = {
      templateId,
      version,
      ext,
      url: `/assets/cards/${collection}/${file}`,
    };

    const current = artwork[templateId];

    // Prefer the newest version.
    // If versions are equal, prefer WebP.
    if (
      !current ||
      candidate.version > current.version ||
      (
        candidate.version === current.version &&
        candidate.ext === '.webp' &&
        current.ext !== '.webp'
      )
    ) {
      artwork[templateId] = candidate;
    }
  }
}

const entries = Object.values(artwork)
  .sort((a, b) => a.templateId.localeCompare(b.templateId));

const generated = `// AUTO-GENERATED by scripts/sync-card-art.mjs
// Do not edit this file manually.

export const GENERATED_CARD_ART: Readonly<Record<string, string>> = Object.freeze({
${entries
  .map(({ templateId, url }) => `  '${templateId}': '${url}',`)
  .join('\n')}
});
`;

fs.writeFileSync(OUTPUT, generated, 'utf8');

console.log('');
console.log('==========================================');
console.log(' NEXA // CARD ART SYNC');
console.log('==========================================');
console.log(` Artes encontradas: ${entries.length}`);
console.log(` Arquivo gerado: src/config/cardArt.generated.ts`);
console.log('==========================================');
console.log('');

for (const { templateId, url } of entries) {
  console.log(`✓ ${templateId} -> ${url}`);
}